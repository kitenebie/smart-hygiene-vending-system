$ErrorActionPreference = 'Stop'
$pgBin = if ($env:PG_BIN) { $env:PG_BIN } else { 'C:\Program Files\PostgreSQL\17\bin' }
$initdb = Join-Path $pgBin 'initdb.exe'
$pgCtl = Join-Path $pgBin 'pg_ctl.exe'
$psql = Join-Path $pgBin 'psql.exe'
$pgIsReady = Join-Path $pgBin 'pg_isready.exe'
foreach ($tool in @($initdb, $pgCtl, $psql, $pgIsReady)) {
  if (!(Test-Path -LiteralPath $tool)) { throw "PostgreSQL tool not found: $tool (set PG_BIN to the PostgreSQL bin folder)" }
}

$tempRoot = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\') + '\'
$clusterRoot = Join-Path $env:TEMP ('4peace-coin-reset-' + [guid]::NewGuid().ToString('N'))
if (![IO.Path]::GetFullPath($clusterRoot).StartsWith($tempRoot, [StringComparison]::OrdinalIgnoreCase)) {
  throw 'Refusing to create a PostgreSQL test cluster outside the temporary directory.'
}
$data = Join-Path $clusterRoot 'data'
$listener = [Net.Sockets.TcpListener]::new([Net.IPAddress]::Loopback, 0)
$listener.Start()
$port = $listener.LocalEndpoint.Port
$listener.Stop()
$started = $false
New-Item -ItemType Directory -Path $clusterRoot | Out-Null

try {
  & $initdb -D $data -U postgres -A trust --no-locale -E UTF8 | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'initdb failed' }
  $logPath = Join-Path $clusterRoot 'postgres.log'
  $startArgs = "-D `"$data`" -o `"-h 127.0.0.1 -p $port`" -l `"$logPath`" -w start"
  Start-Process -FilePath $pgCtl -ArgumentList $startArgs -WindowStyle Hidden | Out-Null
  $started = $true
  $ready = $false
  for ($attempt = 0; $attempt -lt 60; $attempt++) {
    & $pgIsReady -h 127.0.0.1 -p $port *> $null
    if ($LASTEXITCODE -eq 0) { $ready = $true; break }
    Start-Sleep -Milliseconds 250
  }
  if (!$ready) { throw 'PostgreSQL test server did not become ready' }

  $pgArgs = @('-h', '127.0.0.1', '-p', [string]$port, '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1')
  $fixturePath = Join-Path $clusterRoot 'fixtures.sql'
  @'
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE SCHEMA auth;
GRANT USAGE ON SCHEMA auth TO anon, authenticated;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated;
CREATE TABLE public.profiles (id uuid PRIMARY KEY, role text NOT NULL);
CREATE TABLE public.machine_settings (
  id integer PRIMARY KEY,
  updated_at timestamptz NOT NULL DEFAULT now(),
  credit_reset_token bigint NOT NULL DEFAULT 0
);
CREATE TABLE public.gcash_payments (id integer PRIMARY KEY, "Notes" varchar(255) NOT NULL DEFAULT '');
CREATE TABLE public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL,
  level text NOT NULL,
  message text NOT NULL
);
'@ | Set-Content -LiteralPath $fixturePath -Encoding utf8
  & $psql @pgArgs -f $fixturePath | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'Fixture setup failed' }

  $repoRoot = Split-Path -Parent $PSScriptRoot
  & $psql @pgArgs -f (Join-Path $repoRoot 'supabase\migrations\20261113000000_legacy_schema_delta.sql') | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'Schema delta failed' }
  & $psql @pgArgs -f (Join-Path $repoRoot 'supabase\migrations\20261113001000_coin_balance_reset_rpc.sql') | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'Reset RPC migration failed' }

  $seedPath = Join-Path $clusterRoot 'seed.sql'
  @'
INSERT INTO public.profiles VALUES
  ('11111111-1111-4111-8111-111111111111', 'Administrator'),
  ('22222222-2222-4222-8222-222222222222', 'Machine Technician');
INSERT INTO public.machine_settings (id, credit_reset_token) VALUES (1, 7);
DO $$ BEGIN
  IF has_function_privilege('anon', 'public.request_coin_balance_reset()', 'EXECUTE') THEN RAISE EXCEPTION 'anon can execute reset RPC'; END IF;
  IF NOT has_function_privilege('authenticated', 'public.request_coin_balance_reset()', 'EXECUTE') THEN RAISE EXCEPTION 'authenticated cannot execute reset RPC'; END IF;
END $$;
'@ | Set-Content -LiteralPath $seedPath -Encoding utf8
  & $psql @pgArgs -f $seedPath | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'Seed and grant assertions failed' }

  $adminPath = Join-Path $clusterRoot 'admin-call.sql'
  @'
BEGIN;
SET LOCAL ROLE authenticated;
SET LOCAL request.jwt.claim.sub = '11111111-1111-4111-8111-111111111111';
SELECT public.request_coin_balance_reset();
COMMIT;
'@ | Set-Content -LiteralPath $adminPath -Encoding utf8
  & $psql @pgArgs -f $adminPath
  if ($LASTEXITCODE -ne 0) { throw 'Administrator reset request failed' }

  $deniedPath = Join-Path $clusterRoot 'denied-calls.sql'
  @'
BEGIN;
SET LOCAL ROLE authenticated;
SET LOCAL request.jwt.claim.sub = '22222222-2222-4222-8222-222222222222';
DO $$ BEGIN
  BEGIN
    PERFORM public.request_coin_balance_reset();
    RAISE EXCEPTION 'technician reset unexpectedly succeeded';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
END $$;
ROLLBACK;
BEGIN;
SET LOCAL ROLE anon;
SET LOCAL request.jwt.claim.sub = '11111111-1111-4111-8111-111111111111';
DO $$ BEGIN
  BEGIN
    PERFORM public.request_coin_balance_reset();
    RAISE EXCEPTION 'anonymous reset unexpectedly succeeded';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
END $$;
ROLLBACK;
DO $$ BEGIN
  IF (SELECT credit_reset_token FROM public.machine_settings WHERE id=1) <> 8 THEN RAISE EXCEPTION 'denied calls changed reset token'; END IF;
  IF (SELECT count(*) FROM public.notifications) <> 1 THEN RAISE EXCEPTION 'denied calls changed notification count'; END IF;
  IF (SELECT message NOT LIKE 'Coin balance reset requested%' FROM public.notifications LIMIT 1) THEN RAISE EXCEPTION 'reset notification missing'; END IF;
END $$;
'@ | Set-Content -LiteralPath $deniedPath -Encoding utf8
  & $psql @pgArgs -f $deniedPath
  if ($LASTEXITCODE -ne 0) { throw 'Denied-call isolation assertions failed' }
  'PASS: administrator reset increments token and records one notification; technician and anon are denied without state changes.'
}
finally {
  if ($started) {
    $stopArgs = "-D `"$data`" -m fast -w stop"
    Start-Process -FilePath $pgCtl -ArgumentList $stopArgs -WindowStyle Hidden -Wait | Out-Null
  }
  if (Test-Path -LiteralPath $clusterRoot) { Remove-Item -LiteralPath $clusterRoot -Recurse -Force }
}
